"""The tables behind each record of `models.py`, on the MCP's own `Base`, so a migration
autogenerated for the MCP's tables keeps them."""

from sqlalchemy import Boolean
from sqlalchemy import Float
from sqlalchemy import ForeignKey
from sqlalchemy import Index
from sqlalchemy import String
from sqlalchemy import Text
from sqlalchemy.orm import Mapped
from sqlalchemy.orm import mapped_column

from mcp_skeleton.persistence.models import Base


class ClientRow(Base):
    __tablename__: str = "mcp_auth_clients"

    client_id: Mapped[str] = mapped_column(String(255), primary_key=True)
    registration: Mapped[str] = mapped_column(Text)
    created_at: Mapped[float] = mapped_column(Float)


class PendingSignInRow(Base):
    __tablename__: str = "mcp_auth_pending_sign_ins"

    request_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    client_id: Mapped[str] = mapped_column(
        ForeignKey("mcp_auth_clients.client_id", ondelete="CASCADE")
    )
    scopes: Mapped[str] = mapped_column(Text)
    code_challenge: Mapped[str] = mapped_column(String(255))
    redirect_uri: Mapped[str] = mapped_column(Text)
    redirect_uri_provided_explicitly: Mapped[bool] = mapped_column(Boolean)
    state: Mapped[str | None] = mapped_column(Text)
    resource: Mapped[str | None] = mapped_column(Text)
    expires_at: Mapped[float] = mapped_column(Float, index=True)


class AuthorizationCodeRow(Base):
    __tablename__: str = "mcp_auth_authorization_codes"

    code: Mapped[str] = mapped_column(String(64), primary_key=True)
    client_id: Mapped[str] = mapped_column(
        ForeignKey("mcp_auth_clients.client_id", ondelete="CASCADE")
    )
    scopes: Mapped[str] = mapped_column(Text)
    code_challenge: Mapped[str] = mapped_column(String(255))
    redirect_uri: Mapped[str] = mapped_column(Text)
    redirect_uri_provided_explicitly: Mapped[bool] = mapped_column(Boolean)
    resource: Mapped[str | None] = mapped_column(Text)
    subject: Mapped[str] = mapped_column(String(36))
    expires_at: Mapped[float] = mapped_column(Float, index=True)


class TokenRow(Base):
    __tablename__: str = "mcp_auth_tokens"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    family_id: Mapped[str] = mapped_column(String(36), index=True)
    access_token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    refresh_token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    client_id: Mapped[str] = mapped_column(
        ForeignKey("mcp_auth_clients.client_id", ondelete="CASCADE")
    )
    scopes: Mapped[str] = mapped_column(Text)
    resource: Mapped[str | None] = mapped_column(Text)
    subject: Mapped[str] = mapped_column(String(36), index=True)
    access_token_expires_at: Mapped[float] = mapped_column(Float)
    refresh_token_expires_at: Mapped[float] = mapped_column(Float, index=True)
    revoked_at: Mapped[float | None] = mapped_column(Float)


class CredentialRow(Base):
    __tablename__: str = "mcp_auth_credentials"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    username: Mapped[str] = mapped_column(String(320), unique=True)
    # Encrypted with the store's key: a copy of the database alone does not give it away.
    password: Mapped[str] = mapped_column(Text)


class FailedSignInRow(Base):
    __tablename__: str = "mcp_auth_failed_sign_ins"
    __table_args__: tuple[Index] = (
        Index("ix_mcp_auth_failed_sign_ins_username_at", "username", "at"),
    )

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    username: Mapped[str] = mapped_column(String(320))
    at: Mapped[float] = mapped_column(Float)
