interface Selection {
  readonly name: string;
  readonly variables: { readonly tools_preset?: string[]; readonly tools_enabled?: string[] };
  readonly tools: readonly ToolName[];
}

const READ_ONLY_TOOLS: readonly ToolName[] = [
  'search_emails',
  'fetch_next_search_pages',
  'open_email',
  'list_mailboxes_and_directories',
  'list_categories',
  'lookup_contacts',
];

const SELECTIONS: readonly Selection[] = [
  { name: 'defaults', variables: {}, tools: toolsInGroup('mail') },
  ...TOOL_GROUPS.map((group) => ({
    name: `preset_${group}`,
    variables: { tools_preset: [group] },
    tools: toolsInGroup(group),
  })),
  {
    name: 'preset_mail_calendar',
    variables: { tools_preset: ['mail', 'calendar'] },
    tools: [...toolsInGroup('mail'), ...toolsInGroup('calendar')],
  },
  { name: 'read_only', variables: { tools_enabled: [...READ_ONLY_TOOLS] }, tools: READ_ONLY_TOOLS },
  ...TOOL_NAMES.map((tool) => ({
    name: `tool_${tool}`,
    variables: { tools_enabled: [tool] },
    tools: [tool],
  })),
];

const hclList = (values: readonly string[]) => `[${values.map((v) => `"${v}"`).join(', ')}]`;

// `terraform fmt` aligns the `=` of consecutive attributes, so the generated file pads names.
const hclAttributes = (indent: string, attributes: [string, string][]) => {
  const width = Math.max(...attributes.map(([name]) => name.length));
  return attributes.map(([name, value]) => `${indent}${name.padEnd(width)} = ${value}`).join('\n');
};

const selectionRun = (selection: Selection, sharedMailboxes: boolean) => {
  const expected = resolveGraphPermissions({
    mode: McpBackendType.MicrosoftGraph,
    tools: new Set(selection.tools),
    sharedMailboxes,
  });
  const variables: [string, string][] = [
    ...Object.entries(selection.variables).map(([name, value]): [string, string] => [
      name,
      hclList(value),
    ]),
    ...(sharedMailboxes ? [] : [['delegated_access_scan', '"disabled"'] as [string, string]]),
  ];
  const label = `${selection.name}_shared_mailboxes_${sharedMailboxes ? 'on' : 'off'}`;
  return [
    `run "${label}" {`,
    '  command = plan',
    '',
    ...(variables.length ? ['  variables {', hclAttributes('    ', variables), '  }', ''] : []),
    '  assert {',
    hclAttributes('    ', [
      ['condition', `local.graph_scopes == toset(${hclList(expected)})`],
      [
        'error_message',
        `"the server requests ${expected.join(',')} for ${label}, this module selected \${join(",", sort(local.graph_scopes))}"`,
      ],
    ]),
    '  }',
    '}',
  ].join('\n');
};

// Every scope a selection can register, so the mocked Graph service principal knows its id.
const ALL_PERMISSIONS = [
  ...new Set([
    ...BASE_PERMISSIONS,
    ...SHARED_MAILBOX_PERMISSIONS,
    ...TOOL_NAMES.flatMap((name) => TOOL_DECLARATIONS[name].permissions),
    ...Object.values(SHARED_COUNTERPARTS),
  ]),
].sort();

