import {
  BASE_PERMISSIONS,
  REPLACES,
  SHARED_COUNTERPARTS,
  SHARED_MAILBOX_PERMISSIONS,
} from './graph-permissions';
import { TOOL_DECLARATIONS, TOOL_GROUPS, TOOL_NAMES, toolsInGroup } from './tool-declarations';

export const TERRAFORM_REGISTRY_PATH =
  'deploy/terraform/azure/outlook-semantic-mcp-entra-application/registry.generated.tf.json';

// The Entra module applies the same permission rule as `resolveScopes`, from these locals. The
// mode is left out: Unique mode adds only Mail.Read, which every deployment requests already.
export const renderTerraformRegistry = (): string =>
  `${JSON.stringify(
    {
      '//': 'Generated by `pnpm codegen` from src/config. Do not edit.',
      locals: [
        {
          tool_registry: TOOL_NAMES.map((name) => ({
            name,
            permissions: [...TOOL_DECLARATIONS[name].permissions],
          })),
          tool_names: TOOL_NAMES,
          presets: Object.fromEntries(TOOL_GROUPS.map((group) => [group, toolsInGroup(group)])),
          base_permissions: BASE_PERMISSIONS,
          shared_mailbox_permissions: SHARED_MAILBOX_PERMISSIONS,
          shared_counterparts: SHARED_COUNTERPARTS,
          replaces: REPLACES,
        },
      ],
    },
    null,
    2,
  )}\n`;
