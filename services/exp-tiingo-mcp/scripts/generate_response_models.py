"""Generate response models for every exposed operation from the vendored spec.

Run from the project root: `uv run scripts/generate_response_models.py`.
"""

import json
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Any

import yaml

from tiingo_mcp.openapi.routes import EXPOSED

SERVICE = Path(__file__).resolve().parents[1]
PACKAGE = SERVICE / "src/tiingo_mcp"
# Fields a tool returns for a model; the rest is pruned from the spec before codegen.
FIELDS = {"DailyPriceBar": ("date", "open", "high", "low", "close", "volume", "adjClose")}
IGNORED_KEYS = {
    "example", "examples", "discriminator", "format",
    "maxLength", "minLength", "pattern", "enum", "default",
}  # fmt: skip


def response_root(operation: dict[str, Any]) -> str | None:
    """Schema name of the operation's JSON response (or its list items), if it has one."""
    schema = operation["responses"]["200"]["content"]["application/json"]["schema"]
    schema = schema.get("items", schema)
    return schema["$ref"].rsplit("/", 1)[-1] if "$ref" in schema else None


def main() -> None:
    spec = yaml.safe_load((PACKAGE / "openapi/tiingo-openapi.yml").read_text())
    schemas = spec["components"]["schemas"]
    operations = {
        operation["operationId"]: operation
        for path_item in spec["paths"].values()
        for operation in path_item.values()
        if isinstance(operation, dict) and "operationId" in operation
    }
    roots = {response_root(operations[operation_id]) for operation_id in EXPOSED} - {None}
    selected: dict[str, Any] = {}

    def clean(value: Any) -> Any:  # noqa: ANN401
        if isinstance(value, list):
            return [clean(item) for item in value]
        if not isinstance(value, dict):
            return value
        # Responses keep wire-format timestamps as strings and carry no input constraints.
        return {
            key: clean_properties(item) if key == "properties" else clean(item)
            for key, item in value.items()
            if key not in IGNORED_KEYS and not key.startswith("x-")
        }

    def clean_properties(properties: dict[str, Any]) -> dict[str, Any]:
        # Property names are field names, not schema keywords, so none is dropped.
        return {name: clean(prop) for name, prop in properties.items()}

    def slim(name: str, schema: dict[str, Any]) -> dict[str, Any]:
        if name not in FIELDS:
            return schema
        properties = schema["properties"]
        missing = set(FIELDS[name]) - properties.keys()
        assert not missing, f"{name}: spec has no {sorted(missing)}"
        return {**schema, "properties": {key: properties[key] for key in FIELDS[name]}}

    def visit(value: Any) -> None:  # noqa: ANN401
        if isinstance(value, list):
            for item in value:
                visit(item)
        elif isinstance(value, dict):
            if "$ref" in value:
                name = value["$ref"].rsplit("/", 1)[-1]
                if name not in selected:
                    selected[name] = slim(name, clean(schemas[name]))
                    visit(selected[name])
            for item in value.values():
                visit(item)

    for name in sorted(roots):
        visit({"$ref": f"#/components/schemas/{name}"})
    with TemporaryDirectory() as directory:
        source = Path(directory) / "tiingo-responses.json"
        source.write_text(
            json.dumps(
                {
                    "openapi": "3.0.3",
                    "info": {"title": "Tiingo responses", "version": "1"},
                    "paths": {},
                    "components": {"schemas": selected},
                }
            )
        )
        subprocess.run(
            [
                sys.executable, "-m", "datamodel_code_generator",
                "--input", str(source),
                "--input-file-type", "openapi",
                "--output", str(PACKAGE / "models/vendor_responses.py"),
                "--output-model-type", "pydantic_v2.BaseModel",
                "--target-python-version", "3.12",
                "--use-union-operator",
                "--use-standard-collections",
                "--collapse-root-models",
                "--disable-timestamp",
                "--custom-file-header", "# generated by datamodel-codegen\n# ruff: noqa: E501",
                "--formatters", "ruff-check", "ruff-format",
            ],
            check=True,
        )  # fmt: skip


if __name__ == "__main__":
    main()
